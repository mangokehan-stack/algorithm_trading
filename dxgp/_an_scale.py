"""把 08:02 那轮的空闲探针读数与解析段读数放在同一把尺子上

空闲探针（V2.6.123, 每次取数开始跑一轮，纯 CPU，与取数无关）:
  空循环30万次 = 0.026 秒 (基线 0.013, 慢 2.0 倍)
  dict 10万次  = 0.008 秒 (基线 0.005, 慢 1.6 倍)
  clock 2万次  = 0.002 秒 (基线 0.002, 慢 1.0 倍)

解析段（同一时刻的不同负载）:
  空循环5万次 均摊 0.5369 秒 (基线 0.0022, 244 倍)
"""

rows = [
    ('空闲探针 空循环30万', 0.026, 0.013),
    ('空闲探针 dict10万', 0.008, 0.005),
    ('空闲探针 clock2万', 0.002, 0.002),
    ('解析段 空循环5万(均摊)', 0.5369, 0.0022),
    ('解析段 空循环5万(最长)', 10.0007, 0.0022),
]

print('%-26s %10s %10s %8s' % ('负载', '实测(秒)', '基线(秒)', '倍慢'))
for name, got, base in rows:
    print('%-26s %10.4f %10.4f %8.1f' % (name, got, base, got / base))

print()
print('=== 归一到"同一次调用"的口径 ===')
# 空循环30万 = 6 x (5万)。若线性，则 5万 应为 0.026/6 = 0.00433
idle_50k = 0.026 / 6.0
print('空闲探针 5万次 推算 = %.5f 秒 (与解析段的 0.5369 秒同口径)' % idle_50k)
print('解析段 均摊 5万次      = 0.5369 秒')
print('=> 解析段比空闲环境慢 %.0f 倍' % (0.5369 / idle_50k))
print()
print('即: 空闲时解释器只慢 2.0 倍, 解析期间慢到 %.0f 倍' % (0.5369 / idle_50k))
print('两者相差 %.0f 倍 —— 这才是真正要解释的量' % (0.5369 / idle_50k / 2.0))
